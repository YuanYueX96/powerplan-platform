"""生成示例算例（6 节点 / 24 时段），用于算法自检与前后端联调

节点规模刻意做小：Gurobi 受限许可证上限为 2000 变量 / 2000 约束。
"""
from __future__ import annotations

import csv
import os

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "sample")

NODES = ["N1", "N2", "N3", "N4", "N5", "N6"]
SHARE = {"N1": 0.30, "N2": 0.22, "N3": 0.18, "N4": 0.12, "N5": 0.10, "N6": 0.08}

LOAD = [700, 690, 680, 690, 720, 760, 810, 850, 870, 880, 870, 840,
        820, 800, 830, 870, 910, 940, 960, 930, 890, 840, 790, 740]

# 线路: 名称, 首端, 末端, 容量MW, 电抗标幺值
LINES = [
    ("L1", "N1", "N2", 400, 0.050),
    ("L2", "N2", "N3", 300, 0.060),
    ("L3", "N3", "N4", 300, 0.050),
    ("L4", "N1", "N5", 300, 0.080),
    ("L5", "N5", "N6", 250, 0.070),
    ("L6", "N2", "N5", 250, 0.090),
]

# 机组: 序号,名称,类型,装机容量,爬坡,最小技术出力,所在节点,可用小时,充效率,放效率,投建成本,运行成本,是否待建
UNITS = [
    (1, "燃煤A", 1, 600, 200, 180, "N1", "", "", "", 0,       320, 0),
    (2, "燃煤B", 1, 350, 120, 105, "N2", "", "", "", 0,       380, 0),
    (3, "燃气C", 2, 200, 120, 40,  "N3", "", "", "", 0,       550, 0),
    (4, "光伏D", 4, 200, "",  0,   "N4", "", "", "", 0,         5, 0),
    (5, "风电E", 5, 150, "",  0,   "N5", "", "", "", 0,         5, 0),
    (6, "储能F", 6, 50,  "",  0,   "N1", 2, 95, 95,  0,        15, 0),
    (7, "光伏G", 4, 300, "",  0,   "N6", "", "", "", 2_800_000, 5, 1),
    (8, "风电H", 5, 200, "",  0,   "N5", "", "", "", 4_200_000, 5, 1),
    (9, "储能I", 6, 100, "",  0,   "N3", 2, 92, 92,  1_200_000, 15, 1),
    (10, "燃气J", 2, 300, 150, 90, "N6", "", "", "", 2_600_000, 550, 1),
]

TIES = [(1, "区外X1", "N1"), (2, "区外X2", "N2")]
TIE_FC = {
    "区外X1": [110, 110, 110, 110, 110, 110, 120, 130, 140, 150, 150, 145,
               140, 140, 145, 150, 155, 160, 160, 150, 140, 130, 120, 115],
    "区外X2": [60, 60, 60, 60, 60, 60, 65, 70, 75, 80, 80, 80,
               75, 75, 80, 80, 85, 90, 90, 85, 80, 75, 70, 65],
}

PV_D = [0, 0, 0, 0, 0, 0, 10, 40, 90, 140, 170, 190,
        200, 185, 160, 120, 70, 25, 5, 0, 0, 0, 0, 0]
WIND_E = [90, 95, 100, 105, 110, 105, 95, 85, 75, 65, 55, 50,
          45, 50, 55, 60, 70, 80, 90, 95, 100, 95, 92, 90]
PV_G = [0, 0, 0, 0, 0, 0, 15, 60, 135, 210, 255, 285,
        300, 278, 240, 180, 105, 38, 8, 0, 0, 0, 0, 0]
WIND_H = [120, 127, 133, 140, 147, 140, 127, 113, 100, 87, 73, 67,
          60, 67, 73, 80, 93, 107, 120, 127, 133, 127, 123, 120]

RES_FC = {"光伏D": PV_D, "风电E": WIND_E, "光伏G": PV_G, "风电H": WIND_H}

BUDGET = 1.0e9
C_CURT = 500.0


def _w(name, header, rows):
    os.makedirs(BASE, exist_ok=True)
    with open(os.path.join(BASE, name), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def main():
    _w("节点.csv", ["序号", "节点名称"],
       [[i + 1, n] for i, n in enumerate(NODES)])

    _w("线路.csv", ["序号", "线路名称", "首端节点", "末端节点", "线路容量", "电抗标幺值"],
       [[i + 1, n, f, t, c, x] for i, (n, f, t, c, x) in enumerate(LINES)])

    _w("机组.csv", ["序号", "机组名称", "机组类型", "装机容量", "爬坡速率", "最小技术出力",
                    "所在节点", "可用小时数", "储能充电效率", "储能放电效率",
                    "投建成本", "运行成本", "是否待建"],
       [list(r) for r in UNITS])

    _w("联络线.csv", ["序号", "联络线名称", "所在节点"], [list(r) for r in TIES])

    rows = []
    for t in range(1, 25):
        tot = LOAD[t - 1]
        for n in NODES:
            rows.append([n, t, round(tot * SHARE[n], 3)])
    _w("负荷预测.csv", ["节点名称", "时段", "节点负荷"], rows)

    rows = []
    for unit, prof in RES_FC.items():
        for t in range(1, 25):
            rows.append([unit, t, prof[t - 1]])
    _w("新能源预测.csv", ["新能源机组名称", "时段", "新能源出力预测"], rows)

    rows = []
    for tie, prof in TIE_FC.items():
        for t in range(1, 25):
            rows.append([tie, t, prof[t - 1]])
    _w("区外来电预测.csv", ["联络线名称", "时段", "联络线预测"], rows)

    _w("规划经济数据.csv", ["投资上限", "弃新能源惩罚"], [[BUDGET, C_CURT]])

    print("示例算例已生成:", BASE)


if __name__ == "__main__":
    main()
